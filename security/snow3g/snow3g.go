func s1(w uint32) uint32 {
	srw0 := srBox[(w>>24)&0xff]
	srw1 := srBox[(w>>16)&0xff]
	srw2 := srBox[(w>>8)&0xff]
	srw3 := srBox[w&0xff]

	r0 := uint8((mulx(srw0, 0x1b)) ^ (srw1) ^ (srw2) ^ ((mulx(srw3, 0x1b)) ^ srw3))
	r1 := uint8(((mulx(srw0, 0x1b)) ^ srw0) ^ (mulx(srw1, 0x1b)) ^ (srw2) ^ (srw3))
	r2 := uint8((srw0) ^ ((mulx(srw1, 0x1b)) ^ srw1) ^ (mulx(srw2, 0x1b)) ^ (srw3))
	r3 := uint8((srw0) ^ (srw1) ^ ((mulx(srw2, 0x1b)) ^ srw2) ^ (mulx(srw3, 0x1b)))

	return (uint32(r0)<<24 | uint32(r1)<<16 | uint32(r2)<<8 | uint32(r3))
}

func s2(w uint32) uint32 {
	sqw0 := sqBox[(w>>24)&0xff]
	sqw1 := sqBox[(w>>16)&0xff]
	sqw2 := sqBox[(w>>8)&0xff]
	sqw3 := sqBox[w&0xff]

	r0 := (mulx(sqw0, 0x69)) ^ (sqw1) ^ (sqw2) ^ ((mulx(sqw3, 0x69)) ^ sqw3)
	r1 := ((mulx(sqw0, 0x69)) ^ sqw0) ^ (mulx(sqw1, 0x69)) ^ (sqw2) ^ (sqw3)
	r2 := (sqw0) ^ ((mulx(sqw1, 0x69)) ^ sqw1) ^ (mulx(sqw2, 0x69)) ^ (sqw3)
	r3 := (sqw0) ^ (sqw1) ^ ((mulx(sqw2, 0x69)) ^ sqw2) ^ (mulx(sqw3, 0x69))

	return (uint32(r0)<<24 | uint32(r1)<<16 | uint32(r2)<<8 | uint32(r3))
}

