func TestPDNDisconnectRequestErrorCases(t *testing.T) {
	t.Parallel()

	var nilMsg *msg.PDNDisconnectRequest

	if got := nilMsg.MarshalLen(); got != 0 {
		t.Errorf("nil MarshalLen = %d, want 0", got)
	}

	err := nilMsg.MarshalTo(nil)
	if err == nil {
		t.Fatal("nil MarshalTo = nil, want error")
	}
	if !errors.Is(err, ie.ErrNilIE) {
		t.Errorf("nil MarshalTo = %v, want wrapped %T", err, ie.ErrNilIE)
	}

	local := &msg.PDNDisconnectRequest{}
	buf := make([]byte, 1)
	if err := local.MarshalTo(buf); !errors.Is(err, io.ErrShortBuffer) {
		t.Errorf("short buffer = %v, want %T", err, io.ErrShortBuffer)
	}

	var decoded msg.PDNDisconnectRequest

	// Truncated ESM header (2 bytes, need 3).
	err = decoded.UnmarshalBinary([]byte{0xA2, 0x01})
	if !errors.Is(err, io.ErrUnexpectedEOF) {
		t.Fatalf("truncated header = %v, want %T", err, io.ErrUnexpectedEOF)
	}

	// Invalid PD in 3-octet header.
	err = decoded.UnmarshalBinary([]byte{0xAA, 0x01, 0xD2})
	if !errors.Is(err, ie.ErrInvalidValue) {
		t.Fatalf("invalid PD = %v, want wrapped %T", err, ie.ErrInvalidValue)
	}

	// Valid header but no payload — PDNDisconnectRequest has no positional mandatory IEs,
	// so this is a valid 3-octet message.
	err = decoded.UnmarshalBinary([]byte{0xA2, 0x01, 0xD2})
	if err != nil {
		t.Fatalf("valid header only should succeed, got: %v", err)
	}
}

func TestPDNDisconnectRequestParseHelper(t *testing.T) {
	t.Parallel()

	h := msg.EsmHeader{
		BearerIdentity:               0x05,
		ProtocolDiscriminator:        byte(msg.PdEsm),
		ProcedureTransactionIdentity: 0x06,
		MsgType:                      msg.ESMPDNDisconnectRequest,
	}

	esmContainer := ie.NewESMMessageContainer([]byte{0x06, 0xD0})

	m := msg.NewPDNDisconnectRequest(esmContainer)
	m.EsmHeader = h

	buf := make([]byte, m.MarshalLen())
	if err := m.MarshalTo(buf); err != nil {
		t.Fatalf("MarshalTo failed: %v", err)
	}

	parsed, err := msg.ParsePDNDisconnectRequest(buf)
	if err != nil {
		t.Fatalf("ParsePDNDisconnectRequest failed: %v", err)
	}

	if parsed == nil {
		t.Fatal("ParsePDNDisconnectRequest returned nil")
	}

	if parsed.ESMMessageContainer == nil {
		t.Fatal("ESMMessageContainer is nil")
	}

	if !parsed.IsRequest() {
		t.Error("IsRequest = false, want true")
	}

	if parsed.EsmHeader.BearerIdentity != 0x05 {
		t.Errorf("BearerIdentity = %#02x, want 0x05", parsed.EsmHeader.BearerIdentity)
	}
}
