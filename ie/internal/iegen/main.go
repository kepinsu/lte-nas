// Command iegen generates the IE definitions and constructors.
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"maps"
	"os"
	"slices"
	"strconv"
	"strings"
)

const (
	catalogueHeader    = "kind,name,clause,format,minLength,maxLength"
	taggedUsagesHeader = "kind,tag,clause"
)

type usage struct {
	kind       string
	tag        uint8
	definition []string
}

type taggedFormat struct {
	format int
	length int
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	rows, err := readCSV("internal/iegen/catalogue.csv", catalogueHeader)
	if err != nil {
		return err
	}
	usageRows, err := readCSV("internal/iegen/tagged_usages.csv", taggedUsagesHeader)
	if err != nil {
		return err
	}
	usages, err := parseTaggedUsages(rows, usageRows)
	if err != nil {
		return err
	}

	catalogue, constructors, tests, err := generateCatalogue(rows, usages)
	if err != nil {
		return err
	}
	tagged, err := generateTaggedFormats(usages)
	if err != nil {
		return err
	}
	for _, file := range []struct {
		name string
		data []byte
	}{
		{"catalogue_generated.go", catalogue},
		{"constructors_generated.go", constructors},
		{"constructors_generated_test.go", tests},
		{"tagged_generated.go", tagged},
	} {
		data, err := format.Source(file.data)
		if err != nil {
			return fmt.Errorf("format %s: %w", file.name, err)
		}
		if err := os.WriteFile(file.name, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func generateCatalogue(rows [][]string, usages []usage) ([]byte, []byte, []byte, error) {
	byClause := make(map[string][]string, len(rows)-1)
	for _, row := range rows[1:] {
		if len(row) != 6 || byClause[row[2]] != nil {
			return nil, nil, nil, fmt.Errorf("invalid or duplicate catalogue row: %v", row)
		}
		if _, _, _, err := envelope(row); err != nil {
			return nil, nil, nil, fmt.Errorf("%s: %w", row[0], err)
		}
		byClause[row[2]] = row
	}

	const header = "// Code generated by go generate; DO NOT EDIT.\n\npackage ie\n\n"
	var catalogue, constructors, tests bytes.Buffer
	catalogue.WriteString(header)
	constructors.WriteString(header)
	tests.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage ie_test\n\nimport (\"bytes\"; \"testing\"; \"lte-nas/ie\")\n\n")

	catalogue.WriteString("// definitionKind identifies an internal TS 24.301 clause 9.9 value envelope.\n")
	catalogue.WriteString("type definitionKind uint8\n\nconst (\n\tunknownDefinition definitionKind = iota\n")
	for _, row := range rows[1:] {
		fmt.Fprintf(&catalogue, "\t%sDefinition\n", row[0])
	}
	catalogue.WriteString(")\n\nvar _definitions = [...]definition{\n\tunknownDefinition: {},\n")
	for _, row := range rows[1:] {
		formatName, minLength, maxLength, err := envelope(row)
		if err != nil {
			return nil, nil, nil, err
		}
		fmt.Fprintf(&catalogue, "\t%sDefinition: {name: %q, clause: %q, format: IEFormat%s, minLength: %d, maxLength: %d},\n", row[0], row[1], row[2], formatName, minLength, maxLength)
	}
	catalogue.WriteString("}\n")

	constructors.WriteString("// NoTag denotes a positional IE. Tagged constructors return the actual on-wire IEI in IE.Kind.\nconst (\n\tNoTag Kind = 0\n")
	for _, usage := range usages {
		fmt.Fprintf(&constructors, "\t// %s is the IEI for %s (TS 24.301 clause %s).\n\t%s Kind = 0x%02x\n", usage.kind, usage.definition[1], usage.definition[2], usage.kind, usage.tag)
	}
	constructors.WriteString(")\n\n")

	tests.WriteString("func TestTaggedConstructors(t *testing.T) { t.Parallel(); for _, tc := range []struct { name string; kind ie.Kind; format ie.IEFormat; value func() *ie.IE; payload []byte }{\n")
	for _, usage := range usages {
		argument, payload := constructorArgument(usage.definition)
		formatName, _, _, err := envelope(usage.definition)
		if err != nil {
			return nil, nil, nil, err
		}
		fmt.Fprintf(&constructors, "// New%s creates the tagged %s IE (TS 24.301 clause %s).\nfunc New%s(%s) *IE { return newTagged(%sDefinition, %s, %s) }\n\n", usage.kind, usage.definition[1], usage.definition[2], usage.kind, argument, usage.definition[0], usage.kind, constructorValue(usage.definition))
		fmt.Fprintf(&tests, "{name: %q, kind: ie.%s, format: ie.IEFormat%s, value: func() *ie.IE { return ie.New%s(%s) }, payload: %s},\n", usage.kind, usage.kind, formatName, usage.kind, payload, expectedPayload(usage.definition))
	}
	tests.WriteString("} { t.Run(tc.name, func(t *testing.T) { t.Parallel(); got := tc.value(); if got.Kind != tc.kind || got.Format != tc.format || !bytes.Equal(got.Payload, tc.payload) { t.Fatalf(\"constructor = %+v\", got) }; wire, err := got.Marshal(); if err != nil || len(wire) == 0 || wire[0]&tagMask(tc.format) != byte(tc.kind) { t.Fatalf(\"Marshal = %x, %v\", wire, err) } }) } }\n\n")

	tests.WriteString("func TestPositionalConstructors(t *testing.T) { t.Parallel(); for _, tc := range []struct { name string; format ie.IEFormat; value func() *ie.IE; payload []byte }{\n")
	for _, row := range rows[1:] {
		argument, payload := constructorArgument(row)
		formatName, _, _, err := envelope(row)
		if err != nil {
			return nil, nil, nil, err
		}
		fmt.Fprintf(&constructors, "// NewPositional%s creates a positional %s IE (TS 24.301 clause %s).\nfunc NewPositional%s(%s) *IE { return newPositional(%sDefinition, %s) }\n\n", row[0], row[1], row[2], row[0], argument, row[0], constructorValue(row))
		fmt.Fprintf(&tests, "{name: %q, format: ie.IEFormat%s, value: func() *ie.IE { return ie.NewPositional%s(%s) }, payload: %s},\n", row[0], formatName, row[0], payload, expectedPayload(row))
	}
	tests.WriteString("} { t.Run(tc.name, func(t *testing.T) { t.Parallel(); got := tc.value(); if got.Kind != ie.NoTag || got.Format != tc.format || !bytes.Equal(got.Payload, tc.payload) { t.Fatalf(\"constructor = %+v\", got) }; wire, err := got.Marshal(); if err != nil { t.Fatal(err) }; if tc.format == ie.IEFormatOne { wire[0] &= 0x0f }; if bytes.Equal(wire, tc.payload) == false && tc.format != ie.IEFormatFour && tc.format != ie.IEFormatSix { t.Fatalf(\"Marshal = %x, want %x\", wire, tc.payload) } }) } }\n\nfunc tagMask(format ie.IEFormat) byte { if format == ie.IEFormatOne { return 0xf0 }; return 0xff }\n")

	return catalogue.Bytes(), constructors.Bytes(), tests.Bytes(), nil
}

func constructorArgument(row []string) (string, string) {
	_, minLength, maxLength, _ := envelope(row)
	argument := fmt.Sprintf("make([]byte, %d)", minLength)
	if minLength == 1 && maxLength == 1 {
		argument = "0"
	}
	return argumentType(row), argument
}

func argumentType(row []string) string {
	_, minLength, maxLength, _ := envelope(row)
	if minLength == 1 && maxLength == 1 {
		switch row[0] {
		case "EMMCause":
			return "value MmCause"
		case "ESMCause":
			return "value SmCause"
		default:
			return "value uint8"
		}
	}
	return "payload []byte"
}

func constructorValue(row []string) string {
	_, minLength, maxLength, _ := envelope(row)
	if minLength != 1 || maxLength != 1 {
		return "payload"
	}
	switch row[0] {
	case "EMMCause", "ESMCause":
		return "[]byte{byte(value)}"
	default:
		return "[]byte{value}"
	}
}

func expectedPayload(row []string) string {
	_, minLength, maxLength, _ := envelope(row)
	if minLength == 1 && maxLength == 1 {
		return "[]byte{0}"
	}
	return fmt.Sprintf("make([]byte, %d)", minLength)
}

func envelope(row []string) (string, int, int, error) {
	if len(row) != 6 {
		return "", 0, 0, fmt.Errorf("invalid catalogue row: %v", row)
	}
	category, err := strconv.Atoi(row[3])
	if err != nil {
		return "", 0, 0, err
	}
	minLength, err := strconv.Atoi(row[4])
	if err != nil {
		return "", 0, 0, err
	}
	maxLength, err := strconv.Atoi(row[5])
	if err != nil {
		return "", 0, 0, err
	}
	formatNames := map[int]string{1: "One", 3: "Three", 4: "Four", 6: "Six"}
	formatName, ok := formatNames[category]
	if !ok || minLength < 0 || maxLength < minLength || maxLength > 65535 ||
		(category == 4 && maxLength > 255) || ((category == 1 || category == 3) && minLength != maxLength) {
		return "", 0, 0, fmt.Errorf("invalid envelope")
	}
	return formatName, minLength, maxLength, nil
}

func parseTaggedUsages(definitions, usageRows [][]string) ([]usage, error) {
	byClause := make(map[string][]string, len(definitions)-1)
	for _, row := range definitions[1:] {
		if len(row) != 6 || byClause[row[2]] != nil {
			return nil, fmt.Errorf("invalid or duplicate catalogue row: %v", row)
		}
		byClause[row[2]] = row
	}
	seenNames := make(map[string]bool, len(usageRows)-1)
	seenBindings := make(map[[2]string]bool, len(usageRows)-1)
	usages := make([]usage, 0, len(usageRows)-1)
	for _, row := range usageRows[1:] {
		if len(row) != 3 || row[0] == "" || seenNames[row[0]] {
			return nil, fmt.Errorf("invalid or duplicate tagged usage: %v", row)
		}
		tag, err := strconv.ParseUint(row[1], 0, 8)
		definition, ok := byClause[row[2]]
		if err != nil || tag == 0 || !ok {
			return nil, fmt.Errorf("invalid tagged usage tag: %v", row)
		}
		format, minLength, _, err := envelope(definition)
		if err != nil {
			return nil, fmt.Errorf("invalid tagged usage definition: %v", row)
		}
		if err := validateTaggedKind(uint8(tag), format, minLength); err != nil {
			return nil, fmt.Errorf("%w: %v", err, row)
		}
		binding := [2]string{strconv.Itoa(int(tag)), row[2]}
		if seenBindings[binding] {
			return nil, fmt.Errorf("invalid or duplicate tagged usage binding: %v", row)
		}
		seenNames[row[0]] = true
		seenBindings[binding] = true
		usages = append(usages, usage{kind: row[0], tag: uint8(tag), definition: definition})
	}
	if len(usages) == 0 {
		return nil, fmt.Errorf("no tagged usages")
	}
	return usages, nil
}

func generateTaggedFormats(usages []usage) ([]byte, error) {
	if len(usages) == 0 {
		return nil, fmt.Errorf("empty tagged usages")
	}
	byTag := make(map[uint8]map[taggedFormat]struct{})
	for _, usage := range usages {
		format, minLength, _, err := envelope(usage.definition)
		if err != nil {
			return nil, err
		}
		length := 0
		if format == "One" || format == "Three" {
			length = minLength
		}
		candidate := taggedFormat{format: formatNumber(format), length: length}
		if byTag[usage.tag] == nil {
			byTag[usage.tag] = make(map[taggedFormat]struct{})
		}
		byTag[usage.tag][candidate] = struct{}{}
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage ie\n\n")
	output.WriteString("type taggedFormat struct { format IEFormat; length uint16 }\n\n")
	output.WriteString("// _taggedFormats contains globally unambiguous wire envelopes.\nvar _taggedFormats = map[Kind]taggedFormat{\n")
	var ambiguous []uint8
	for _, tag := range slices.Sorted(maps.Keys(byTag)) {
		formats := byTag[tag]
		if len(formats) != 1 {
			ambiguous = append(ambiguous, tag)
			continue
		}
		var candidate taggedFormat
		for candidate = range formats {
		}
		fmt.Fprintf(&output, "\t0x%02x: {format: IEFormat%s, length: %d},\n", tag, formatName(candidate.format), candidate.length)
	}
	output.WriteString("}\n\nvar _ambiguousTaggedFormats = map[Kind]struct{}{\n")
	for _, tag := range ambiguous {
		fmt.Fprintf(&output, "\t0x%02x: {},\n", tag)
	}
	output.WriteString("}\n")
	return output.Bytes(), nil
}

func validateTaggedKind(tag uint8, format string, length int) error {
	if tag == 0 || (format == "One" && (tag < 0x80 || tag&0x0f != 0 || length != 1)) ||
		(format != "One" && tag >= 0x80) || (format == "Three" && length == 0) {
		return fmt.Errorf("invalid tagged usage")
	}
	return nil
}

func formatNumber(format string) int {
	return map[string]int{"One": 1, "Two": 2, "Three": 3, "Four": 4, "Six": 6}[format]
}

func formatName(format int) string {
	return map[int]string{1: "One", 2: "Two", 3: "Three", 4: "Four", 6: "Six"}[format]
}

func readCSV(path, header string) ([][]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	rows, readErr := csv.NewReader(f).ReadAll()
	closeErr := f.Close()
	if readErr != nil {
		return nil, readErr
	}
	if closeErr != nil {
		return nil, closeErr
	}
	if len(rows) < 2 || strings.Join(rows[0], ",") != header {
		return nil, fmt.Errorf("invalid or empty CSV: %s", path)
	}
	return rows, nil
}
